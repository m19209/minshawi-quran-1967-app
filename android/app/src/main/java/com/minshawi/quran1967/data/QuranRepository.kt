    fun getSurah(number: Int): Surah? = surahs.find { it.number == number }

    fun searchSurahs(query: String): List<Surah> {
        if (query.isBlank()) return surahs
        val clean = query.trim().lowercase()
        return surahs.filter {
            it.arabicName.contains(clean) || it.englishName.lowercase().contains(clean) || it.number.toString() == clean
        }
    }
